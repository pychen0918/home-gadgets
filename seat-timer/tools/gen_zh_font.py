#!/usr/bin/env python3
"""Generate src/zh_font.h: 1-bit glyph bitmaps for the Chinese text the
e-paper shows. Only the characters actually used are included.

Usage:
  python3 tools/gen_zh_font.py path/to/NotoSansTC[wght].ttf

Font: Noto Sans TC (SIL Open Font License), from
  https://github.com/google/fonts/tree/main/ofl/notosanstc

If you change any on-screen text in src/screen.h, add it to TEXTS below and
re-run this script.
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

# Every string the firmware draws, per font size. Digits are always included.
TEXTS = {
    "XL": ["-"],                    # Ready-screen temperature: digits and minus
    "L": [
        "啟動中…", "計時中", "該站起來了！", "找不到雷達",
        "坐下", "提醒你起身", "分鐘後", "已坐 分鐘", ":", "°C",
        "月日 星期日一二三四五六", "等待網路校時",
        # weather words from wmoText() in src/weather_view.h (Ready screen, large)
        "晴", "晴時多雲", "多雲", "陰", "霧", "毛毛雨", "雨", "大雨", "凍雨", "雪", "陣雨", "陣雪",
        "雷雨", "—",
    ],
    "M": [
        "坐下自動開始計時　今天起身 次",
        "今天起身 次　上限 分鐘",
        "起身離開座位 2 分鐘就會重新計時",
        "/（）日一二三四五六", "等待網路校時",
        "天氣讀取中", "未連網", "今天 –°C　降雨 %",
        "晴", "晴時多雲", "多雲", "陰", "霧", "毛毛雨", "雨", "大雨", "凍雨", "雪", "陣雨", "陣雪",
        "雷雨", "—", "-",
        "（手動模式）",
        "請檢查 LD2410C 接線",
        "TX 接 GPIO16，RX 接 GPIO17",
        "VCC 接 5V，GND 接 GND",
    ],
}
SIZES = {"XL": (72, 700), "L": (30, 700), "M": (18, 500)}  # px, weight
DIGITS = "0123456789"


def glyph_set(name):
    chars = set(DIGITS) | set("".join(TEXTS[name]))
    chars.discard(" ")
    return sorted(chars, key=ord)


def render_font(path, name):
    px, weight = SIZES[name]
    font = ImageFont.truetype(path, px)
    try:
        font.set_variation_by_axes([weight])
    except Exception:
        pass
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in glyph_set(name):
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(font.getlength(ch)))
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        off = len(bitmap)
        stride = (w + 7) // 8
        for y in range(h):
            row = bytearray(stride)
            for x in range(w):
                if img.getpixel((x, y)) >= 128:
                    row[x >> 3] |= 0x80 >> (x & 7)
            bitmap += row
        assert -128 <= x0 <= 127 and -128 <= y0 <= 127 and w < 256 and h < 256 and adv < 256
        glyphs.append((ord(ch), w, h, x0, y0, adv, off, ch))
    space = int(round(font.getlength(" ")))
    return glyphs, bitmap, ascent, descent, space


def emit(path):
    out = [
        "// Generated by tools/gen_zh_font.py from Noto Sans TC (SIL OFL). Do not edit.",
        "#pragma once",
        '#include "zh_text.h"',
        "",
    ]
    for name in SIZES:
        glyphs, bitmap, ascent, descent, space = render_font(path, name)
        out.append(f"static const uint8_t ZH_{name}_BITMAP[] = {{")
        for i in range(0, len(bitmap), 24):
            out.append("  " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const ZhGlyph ZH_{name}_GLYPHS[] = {{")
        for cp, w, h, xo, yo, adv, off, ch in glyphs:
            out.append(f"  {{0x{cp:04x}, {w}, {h}, {xo}, {yo}, {adv}, {off}}},  // {ch}")
        out.append("};")
        out.append(
            f"static const ZhFont ZH_{name} = {{ZH_{name}_BITMAP, ZH_{name}_GLYPHS, "
            f"{len(glyphs)}, {ascent}, {descent}, {space}}};"
        )
        out.append("")
        print(f"{name}: {len(glyphs)} glyphs, {len(bitmap)} bytes", file=sys.stderr)
    target = Path(__file__).resolve().parent.parent / "src" / "zh_font.h"
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    emit(sys.argv[1])
